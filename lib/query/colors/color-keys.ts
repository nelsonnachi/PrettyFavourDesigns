export const colorKeys = {
  // ----------------------------------------------------------
  // Root
  // ----------------------------------------------------------

  all: ["colors"] as const,

  // ----------------------------------------------------------
  // Public active colors
  // ----------------------------------------------------------

  active: () => [...colorKeys.all, "active"] as const,

  // ----------------------------------------------------------
  // Admin colors
  // ----------------------------------------------------------

  admin: () => [...colorKeys.all, "admin"] as const,

  // ----------------------------------------------------------
  // Single color
  // ----------------------------------------------------------

  detail: (id: string) =>
    [...colorKeys.all, "detail", id] as const,
};