// ============================================================
// RATING QUERY KEYS
// ============================================================

export const ratingKeys = {
  // ----------------------------------------------------------
  // Root
  // ----------------------------------------------------------

  all: ["ratings"] as const,

  // ----------------------------------------------------------
  // Ratings belonging to a product
  // ----------------------------------------------------------

  product: (slug: string) =>
    [...ratingKeys.all, "product", slug] as const,

  // ----------------------------------------------------------
  // Single rating
  // ----------------------------------------------------------

  detail: (id: string) =>
    [...ratingKeys.all, "detail", id] as const,
};